//! NT PE-экспорты ядра (`ntoskrnl.exe`)
//!
//! Этот модуль содержит **только** стабильные PE-экспорты в стиле Windows NT
//! (PascalCase, win64 ABI), которые используются внешними модулями:
//! `hal.dll`, boot-драйверы и прочие PE-компоненты.
//!
//! # Архитектура
//!
//! ```text
//!        (внешний PE модуль)
//!    hal.dll / driver.sys / bootvid.dll
//!                 │   imports (IAT)
//!                 ▼
//!     ┌──────────────────────────────┐
//!     │     ntoskrnl.exe exports     │
//!     │       KeBugCheckEx / ...     │
//!     │  ...                         │
//!     └───────────────┬──────────────┘
//!                     │ thin-wrapper
//!                     ▼
//!     ┌──────────────────────────────┐
//!     │    внутренние реализации     │
//!     │ ke::bugcheck::ke_bug_check_ex│
//!     └──────────────────────────────┘
//! ```
//!
//! # Структура модуля
//!
//! Экспорты разбиты по подсистемам ядра (соответствует NT naming conventions):
//!
//! - `ke` — Kernel Executive (`Ke*`)
//! - `mm` — Memory Manager (`Mm*`)
//! - `ex` — Executive (`Ex*`)
//! - `ps` — Process/Thread Manager (`Ps*`)
//! - `io` — I/O Manager (`Io*`)
//! - `ob` — Object Manager (`Ob*`)
//! - `rtl` — Runtime Library (`Rtl*`)
//! - `hal` — HAL exports из ядра (`Hal*`, если требуется)
//!
//! # Отступления и упрощения
//!
//! - Экспорты вводятся минимально необходимым набором для запуска `hal.dll`.
//!
//! # Правила заполнения экспортов (обязательные)
//!
//! В этом модуле формируется публичный контракт `ntoskrnl.exe` для PE-import runtime.
//! Ошибка здесь ломает загрузку `hal.dll`/драйверов и совместимость в целом, поэтому правила жёсткие:
//!
//! - **100% соответствие MSDN/WDK сигнатурам и поведению — главный приоритет, любой ценой.**
//! - **Мы никогда не "упрощаем" экспортируемую сигнатуру** (не добавляем/убираем аргументы,
//!   не меняем типы, calling convention, возвращаемое значение).
//! - Если мы *пока* не можем реализовать функцию корректно — это повод:
//!   - изменить/добавить внутренний API (snake_case) и подсистемы, необходимые для настоящей семантики NT,
//!   - но **не** менять контракт экспорта;
//!   - уведомить пользователя о необходимости изменить внутренний контракт/подсистему.
//! - Каждый экспорт обязан иметь:
//!   - `extern "win64"` + `#[export_name = "..."]`/`#[no_mangle]` (в зависимости от выбранной схемы);
//!   - docstring на русском языке с оригинальным именем NT (например, `/// KeBugCheckEx`);
//!   - **ссылку на MSDN/WDK** на описание именно этой функции (приоритетный источник).
//! - Перед добавлением нового экспорта обязательно:
//!   - сверить точную сигнатуру/ABI/семантику по MSDN/WDK (NT6.1 ориентир);
//!   - убедиться, что в коде нет уже существующего экспорта с тем же NT-именем;
//!   - убедиться, что внутренняя реализация соответствует описанному поведению (или добавлены TODO/блокеры,
//!     но экспорт остаётся NT-совместимым).
//!
//! Источники:
//! - MSDN/WDK (NT6.1): имена экспортов `KeBugCheckEx`, `MmMapIoSpace`, `MmUnmapIoSpace` и т.д.

