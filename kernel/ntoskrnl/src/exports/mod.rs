/// Объявляет thin-wrapper экспортируемой функции с фиксированным PE именем.
///
/// ВАЖНО:
/// - Экспортируемое имя задаётся строкой (как его увидит import resolver).
/// - ABI всегда `extern "win64"`.
/// - Макрос предназначен только для простых прокладок вида `export -> target(args...)`.
#[macro_export]
macro_rules! nt_export_fn {
    (
        $export_name:literal => $wrapper:ident(
            $( $arg:ident : $ty:ty ),* $(,)?
        ) -> $ret:ty = $target:path
    ) => {
        #[unsafe(export_name = $export_name)]
        pub extern "win64" fn $wrapper($( $arg : $ty ),*) -> $ret {
            $target($( $arg ),*)
        }
    };
}

/// Вариант для `unsafe extern "win64"` экспортов.
#[macro_export]
macro_rules! nt_export_unsafe_fn {
    (
        $export_name:literal => $wrapper:ident(
            $( $arg:ident : $ty:ty ),* $(,)?
        ) -> $ret:ty = $target:path
    ) => {
        #[unsafe(export_name = $export_name)]
        pub unsafe extern "win64" fn $wrapper($( $arg : $ty ),*) -> $ret {
            $target($( $arg ),*)
        }
    };
}

