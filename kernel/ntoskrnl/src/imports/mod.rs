//! PE-импорты ядра (`ntoskrnl.exe`)
//!
//! Этот модуль содержит декларации импортов из внешних PE-модулей.
//! Импорты резолвятся через IAT patching при загрузке winload.
//!
//! # Архитектура
//!
//! ```text
//!     ┌──────────────────────────────┐
//!     │    внутренние реализации     │
//!     │       inbv, ke, ...          │
//!     └───────────────┬──────────────┘
//!                     │ использует
//!                     ▼
//!     ┌──────────────────────────────┐
//!     │   ntoskrnl.exe imports       │  <── Этот модуль
//!     │    VidInitialize / ...       │
//!     └───────────────┬──────────────┘
//!                     │   IAT (патчится winload)
//!                     ▼
//!     ┌──────────────────────────────┐
//!     │       bootvid.dll            │
//!     │   hal.dll (будущее)          │
//!     └──────────────────────────────┘
//! ```
//!
//! # Структура модуля
//!
//! - `bootvid` — импорты из bootvid.dll (VidInitialize, VidDisplayString, ...)

