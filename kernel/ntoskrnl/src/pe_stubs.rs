//! PE/COFF runtime stubs
//!
//! Заглушки для символов, требуемых MSVC/PE линковкой:
//! - __chkstk: stack probe для больших стековых аллокаций
//! - _fltused: маркер использования floating point

use core::arch::global_asm;

// =============================================================================
// __chkstk - Stack Probe
// =============================================================================
//
// Windows x64 требует stack probe для стековых аллокаций > 4KB.
// Функция вызывается компилятором автоматически когда локальные переменные
// превышают PAGE_SIZE. Она "прощупывает" каждую страницу стека, чтобы
// гарантировать, что guard page сработает корректно.
//
// В kernel mode мы не используем guard pages в классическом понимании,
// поэтому просто выполняем stack touch для корректной работы.

global_asm!(
    r#"
.global __chkstk

__chkstk:
    // RAX содержит размер аллокации в байтах
    // Нужно проверить каждую страницу от RSP до RSP - RAX
    //
    // Для простоты в kernel mode просто возвращаемся -
    // у нас фиксированные стеки без guard pages.
    // TODO: реализовать proper stack probing если понадобится
    ret
"#
);

// =============================================================================
// _fltused - Floating Point Usage Marker
// =============================================================================
//
// MSVC линкер требует этот символ если в коде используется floating point.
// Значение не важно, просто должен существовать.

#[unsafe(no_mangle)]
#[used]
pub static _fltused: i32 = 0;
